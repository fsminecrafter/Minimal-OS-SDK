/*
 * font.h - text for programs that draw their own pixels.
 *
 * Draws smooth, anti-aliased text into any ARGB8888 pixel buffer with the
 * same OpenType renderer and Inter fonts mosWM and easyui use. When the
 * fonts cannot be read (mosWM is not installed), it falls back to the
 * 8 x 8 bitmap font, scaled by the text size.
 *
 *     #include "font.h"
 *
 *     draw_text(pixels, width, height, 10, 10, "Hello", 0xFFFFFFFF, 1);
 *     int w = text_width("Hello", 2);
 *
 * Sizes match easyui and mosWM: size 1 is 12 px Inter Regular, size 2 and
 * up is 8 x size px Inter Medium. (x, y) is the top-left corner of the
 * text; '\n' starts a new line. Text is alpha-blended with the pixels
 * underneath (the color's top byte is its opacity).
 *
 * Header only. It can be included together with easyui.h. Full reference:
 * docs/font.md.
 */

