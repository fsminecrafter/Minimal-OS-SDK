static ttrend_outline_font_t font__face[2];   /* 0: size 1, 1: size 2 and up */
static void* font__data[2];
static int font__ok[2], font__tried, font__smooth = 1;

/* Loads an .otf/.ttf file for size-1 text (bold = 0) or larger text
 * (bold = 1), replacing Inter. Returns 1 on success, 0 on failure. */
static __attribute__((unused)) int font_load(const char* path, int bold) {
    int slot = bold ? 1 : 0;
    long fd = mos_open(path, SYS_O_RDONLY);
    if (fd <= 0) return 0;
    long size = mos_size(fd);
    uint8_t* data = size > 0 && size <= 8L * 1024 * 1024 ? (uint8_t*)malloc((size_t)size) : 0;
    long got = 0;
    while (data && got < size) {
        long n = mos_read(fd, data + got, (size_t)(size - got));
        if (n <= 0) break;
        got += n;
    }
    mos_close(fd);
    if (!data) return 0;
    ttrend_outline_font_t face;
    if (got != size || ttrend_outline_font_load_memory(&face, data, (size_t)size, 12u) != 0) {
        free(data);
        return 0;
    }
    if (font__data[slot]) free(font__data[slot]);
    font__face[slot] = face;
    font__data[slot] = data;
    font__ok[slot] = 1;
    font__tried = 1;
    return 1;
}

/* 1 (default): smooth text when the fonts are available; 0: always the
 * bitmap font. */
static __attribute__((unused)) void font_set_smooth(int on) { font__smooth = on ? 1 : 0; }

/* The outline font for a text size, or NULL for the bitmap font. */
static ttrend_outline_font_t* font__get(int size) {
    if (!font__smooth) return 0;
    if (!font__tried) {
        font__tried = 1;
        if (!font__ok[0]) font_load(FONT_REGULAR_PATH, 0);
        if (!font__ok[1]) font_load(FONT_MEDIUM_PATH, 1);
    }
    int want = size >= 2 ? 1 : 0;
    ttrend_outline_font_t* f;
    if (font__ok[want]) f = &font__face[want];
    else if (font__ok[!want]) f = &font__face[!want];
    else return 0;
    f->pixel_size = size <= 1 ? 12u : 8u * (uint32_t)size;
    return f;
}

/* 1 when text is drawn with the OpenType renderer, 0 for the bitmap font. */
static __attribute__((unused)) int font_is_smooth(void) { return font__get(1) != 0; }

/* Height of one line of text at this size, in pixels. */
static __attribute__((unused)) int text_height(int size) {
    if (size < 1) size = 1;
    ttrend_outline_font_t* f = font__get(size);
    return f ? (int)(ttrend_outline_ascent(f) + ttrend_outline_descent(f)) : 8 * size;
}

/* Distance from one line to the next. */
static int font__line_step(int size) {
    ttrend_outline_font_t* f = font__get(size);
    int h = f ? (int)ttrend_outline_line_height(f) : 10 * size;
    int t = text_height(size);
    return h > t ? h : t + 2;
}

/* Width in pixels of the widest line of `text`. */
static __attribute__((unused)) int text_width(const char* text, int size) {
    if (size < 1) size = 1;
    ttrend_outline_font_t* f = font__get(size);
    int best = 0;
    while (text && *text) {
        char line[256];
        int n = 0;
        while (text[n] && text[n] != '\n') n++;
        int w;
        if (f) {
            int k = n > 255 ? 255 : n;
            for (int i = 0; i < k; i++) line[i] = text[i];
            line[k] = '\0';
            w = (int)ttrend_outline_text_width(line, f);
        } else {
            w = n * 8 * size;
        }
        if (w > best) best = w;
        text += n;
        if (*text) text++;
    }
    return best;
}

static void font__bitmap_char(uint32_t* px, uint32_t w, uint32_t h, int x, int y,
                              char ch, uint32_t color, int size) {
    unsigned char u = (unsigned char)ch;
    if (u < 32u || u > 126u) u = '?';
    const uint8_t* g = font__glyphs[u - 32u];
    uint32_t a = color >> 24;
    for (int gy = 0; gy < 8; gy++) {
        for (int gx = 0; gx < 8; gx++) {
            if (!(g[gy] & (1u << gx))) continue;
            for (int sy = 0; sy < size; sy++) {
                int py = y + gy * size + sy;
                if (py < 0 || py >= (int)h) continue;
                for (int sx = 0; sx < size; sx++) {
                    int pxx = x + gx * size + sx;
                    if (pxx < 0 || pxx >= (int)w) continue;
                    uint32_t* d = &px[(size_t)py * w + (size_t)pxx];
                    if (a >= 255u) { *d = color; continue; }
                    uint32_t o = *d, r = 255u - a;
                    uint32_t rr = (((color >> 16) & 255u) * a + ((o >> 16) & 255u) * r) / 255u;
                    uint32_t gg = (((color >> 8) & 255u) * a + ((o >> 8) & 255u) * r) / 255u;
                    uint32_t bb = ((color & 255u) * a + (o & 255u) * r) / 255u;
                    *d = (o & 0xFF000000u) | (rr << 16) | (gg << 8) | bb;
                }
            }
        }
    }
}

/* Draws `text` with its top-left corner at (x, y) into a width x height
 * ARGB8888 buffer (rows of `width` pixels), clipped to the buffer. */
static __attribute__((unused)) void draw_text(uint32_t* pixels, uint32_t width, uint32_t height,
                                              int x, int y, const char* text, uint32_t color, int size) {
    if (!pixels || !text || !width || !height) return;
    if (size < 1) size = 1;
    ttrend_outline_font_t* f = font__get(size);
    int step = font__line_step(size);
    while (*text) {
        char line[256];
        int n = 0;
        while (text[n] && text[n] != '\n') n++;
        if (f) {
            int k = n > 255 ? 255 : n;
            for (int i = 0; i < k; i++) line[i] = text[i];
            line[k] = '\0';
            ttrend_outline_surface_t s = { pixels, width, height, width };
            ttrend_outline_draw_text_baseline(&s, x, y + ttrend_outline_ascent(f), line, color, f);
        } else {
            for (int i = 0; i < n; i++)
                font__bitmap_char(pixels, width, height, x + i * 8 * size, y, text[i], color, size);
        }
        y += step;
        text += n;
        if (*text) text++;
    }
}

