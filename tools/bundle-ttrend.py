#!/usr/bin/env python3
"""Regenerates include/easyui_text.h from MOSdesk's ttrend_outline.

    python3 tools/bundle-ttrend.py path/to/MOSdesk

easyui draws text with ttrend_outline, the anti-aliased OpenType renderer
mosWM uses. This copies its header and source into one header (internal
linkage, no file loader) so programs need nothing but include/.
"""
import sys, pathlib
root = pathlib.Path(sys.argv[1]) / 'mosdesk' / 'libraries' / 'ttrend_outline'
head = (root / 'include' / 'ttrend_outline.h').read_text()
src = (root / 'src' / 'ttrend_outline.c').read_text()
src = src.replace('#include "../include/ttrend_outline.h"\n', '')
out = pathlib.Path(__file__).resolve().parent.parent / 'include' / 'easyui_text.h'
out.write_text(
    '/* Generated by tools/bundle-ttrend.py from MOSdesk\'s\n'
    ' * mosdesk/libraries/ttrend_outline (GPL-3.0, like this SDK). Do not edit;\n'
    ' * change it in MOSdesk and regenerate. easyui.h includes this for smooth\n'
    ' * text; every symbol has internal linkage. */\n'
    '#ifndef EASYUI_TEXT_H\n#define EASYUI_TEXT_H\n'
    '#define TTREND_OUTLINE_STATIC\n#define TTREND_OUTLINE_NO_FILE\n\n'
    + head + '\n' + src + '\n#endif /* EASYUI_TEXT_H */\n')
print('wrote', out)
